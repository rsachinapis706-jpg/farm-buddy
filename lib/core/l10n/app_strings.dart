import 'package:farm_buddy/models/enums.dart';

/// Lightweight localisation.
///
/// Deliberately not `flutter_localizations` + ARB codegen: this ships three
/// plain maps, resolves in constant time, needs no build step, and — most
/// importantly — **never throws**. A missing key falls back to English and
/// then to the key itself, so a half-translated build still renders a usable
/// screen instead of a red error box in front of a judge.
///
/// Usage:
/// ```dart
/// final s = ref.watch(stringsProvider);
/// Text(s('home.hero.title'));
/// Text(s.withArgs('home.greeting.morning', {'name': 'Murugan'}));
/// ```
class AppStrings {
  const AppStrings(this.language);

  final AppLanguage language;

  Map<String, String> get _table => switch (language) {
        AppLanguage.english => en,
        AppLanguage.tamil => ta,
        AppLanguage.hindi => hi,
      };

  /// Callable: `s('key')`.
  String call(String key) => _table[key] ?? en[key] ?? key;

  /// Replaces `{placeholders}` in the resolved string.
  String withArgs(String key, Map<String, String> args) {
    String value = call(key);
    args.forEach((String name, String replacement) {
      value = value.replaceAll('{$name}', replacement);
    });
    return value;
  }

  /// `key.one` for n == 1, otherwise `key.other`, with `{n}` substituted.
  String plural(String key, num n) {
    final String suffix = n == 1 ? '.one' : '.other';
    return withArgs('$key$suffix', <String, String>{'n': '$n'});
  }

  /// True when this key has a real translation (used by the language picker
  /// to show a coverage figure honestly).
  bool hasTranslation(String key) => _table.containsKey(key);

  static int coverageOf(AppLanguage language) {
    final Map<String, String> table = switch (language) {
      AppLanguage.english => en,
      AppLanguage.tamil => ta,
      AppLanguage.hindi => hi,
    };
    if (en.isEmpty) return 100;
    return ((table.length / en.length) * 100).round().clamp(0, 100).toInt();
  }

